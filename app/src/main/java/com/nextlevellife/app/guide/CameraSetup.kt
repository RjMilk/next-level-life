package com.nextlevellife.app.guide

/**
 * Установка камеры для упражнений с гирей — в одном месте: гид упражнения ([KettlebellGuides]),
 * подсказка на камере (setupLine в CameraRepPanel) и экран комплекса «Минотавр».
 *
 * Что проверено записями тестировщика и синтетикой:
 * - трастер, мах и тяга сумо считаются ЛИЦОМ к камере; в четверть оборота (≈ 45°) трастер не считается вовсе
 *   (угол колена в кадре 150–177° при настоящем приседе), поэтому «в пол-оборота» здесь не советуем;
 * - руки над головой должны помещаться в кадр: в портретном кадре это примерно 3–3,5 м от телефона на уровне пояса;
 * - тяга в наклоне и становая считаются по наклону корпуса — он виден только сбоку.
 */
object CameraSetup {
    /** Ракурс в гиде (со строчной: «Камера: 3–3,5 м · лицом к камере»). */
    const val FACE_ANGLE = "лицом к камере"
    const val FACE_DISTANCE = "3–3,5 м"

    /** Строка «камера» в гиде: без точки в конце. */
    const val FACE_CAMERA = "Телефон на уровне пояса. Отойди, чтобы руки над головой были в кадре"

    /** Подсказка на камере: трастер, мах, тяга сумо. */
    const val FACE_SETUP = "Встань лицом к телефону, он на уровне пояса, в 3–3,5 м: отойди, чтобы руки над головой были в кадре"

    /** Подсказка на камере: упражнения, которые считаются по наклону корпуса. */
    const val SIDE_SETUP = "Встань боком к телефону, видно всё тело"

    /** Экран комплекса «Минотавр» (трастер, мах, тяга сумо, тяга в наклоне, становая). */
    const val MINOTAUR =
        "Телефон на уровне пояса, в 3–3,5 м. Трастер, мах и тягу сумо делай лицом к телефону — руки над головой " +
            "должны быть в кадре; тягу в наклоне и становую — боком."

    /** Упражнения, которые снимаются лицом к камере. */
    val FACE: Set<String> = setOf("thruster", "swings", "sumo_pull")
}
