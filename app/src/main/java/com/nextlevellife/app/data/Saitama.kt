package com.nextlevellife.app.data

/**
 * Суточный комплекс «Сайтама»: каждый учётный день ([TrustedClock]) — 100 отжиманий, 100 повторений
 * на пресс, 100 приседаний (считает камера) и 10 км бега (Health Connect, тип тренировки «Бег»).
 *
 * - Сотни набираются любыми подходами-повторениями за учётные сутки: отдельные упражнения, подходы
 *   внутри Синди — всё, что записано в дневник с этим `day`. Планка не считается, лишнее на завтра
 *   не переносится.
 * - Бег — сумма дистанции пробежек дня ([ActivityDay.runDistanceM]); порога скорости нет. Нет строки
 *   активности за день — бег не подтверждён (это не «0 км»).
 * - Полный день — все четыре цели. Серия — полные дни подряд (сегодняшний незавершённый — не пропуск),
 *   считается из дневника, отдельного счётчика нет. Дни раньше [META_SINCE] в серию не идут.
 * - За полный день — [BONUS_MS] одной операцией журнала ([OpKind.COMPLEX_REWARD], ключ [bonusKey]);
 *   повторения и бег оплачиваются как обычно. Сила: полный день — завершённый комплекс.
 *
 * Ограничение: подход, начатый до полуночи и сохранённый после, целиком идёт в сутки сохранения
 * (так пишет [Workouts]: день — из снимка времени записи). Деление подхода по времени повторений
 * пока не сделано.
 */
object Saitama {
    const val ID = "saitama"

    /** Повторений каждого упражнения за день. */
    const val REPS_GOAL = 100

    /** Метров бега за день. */
    const val RUN_GOAL_M = 10_000L

    /** Бонус за полный день: 10 минут экранного времени. */
    const val BONUS_MS = 10 * 60_000L

    /** Сколько последних дней (включая сегодня) проверяются на недоплаченный бонус: пробежка может прийти позже. */
    const val CHECK_DAYS = 14

    /** Тип источника операции бонуса в журнале. */
    const val SOURCE_TYPE = "saitama"

    /** meta: учётный день первого расчёта «Сайтамы» — с него идёт серия и платится бонус. Ставится один раз. */
    const val META_SINCE = "saitama_since"

    /** meta-префикс: какие вехи дня уже показаны «нарезкой». */
    const val META_SHOWN_PREFIX = "saitama_shown:"

    /** Упражнения-сотни в порядке экрана. */
    val exercises: List<Exercise> = listOf(Exercises.pushups, Exercises.abs, Exercises.squats)

    /** Ключ идемпотентности бонуса дня [day]: один бонус на день, повторный вызов ничего не платит. */
    fun bonusKey(day: Long): String = "$ID:$day"

    fun shownKey(day: Long): String = "$META_SHOWN_PREFIX$day"
}
